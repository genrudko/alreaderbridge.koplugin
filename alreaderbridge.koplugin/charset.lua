local function normal(enc)
    enc=(enc or ""):lower():gsub("_","-"):gsub("%s+","")
    return aliases[enc] or enc
end
local function utf8_valid(s)
    local i,n=1,#s
    while i<=n do
        local b=s:byte(i)
        if b<128 then i=i+1
        elseif b>=0xC2 and b<=0xDF then
            local c=s:byte(i+1)
            if not c or c<0x80 or c>0xBF then return false end
            i=i+2
        elseif b>=0xE0 and b<=0xEF then
            local c,d=s:byte(i+1,i+2)
            if not d or c<0x80 or c>0xBF or d<0x80 or d>0xBF
              or (b==0xE0 and c<0xA0) or (b==0xED and c>0x9F) then return false end
            i=i+3
        elseif b>=0xF0 and b<=0xF4 then
            local c,d,e=s:byte(i+1,i+3)
            if not e or c<0x80 or c>0xBF or d<0x80 or d>0xBF
              or e<0x80 or e>0xBF or (b==0xF0 and c<0x90)
              or (b==0xF4 and c>0x8F) then return false end
            i=i+4
        else return false end
    end
    return true
end
M.isValidUtf8=utf8_valid
local function decode16(raw,le)
    if #raw%2~=0 then return nil,"incomplete UTF-16 input" end
    local out={}
    local n=0
    local i=1
    while i<=#raw do
        local a,b=raw:byte(i,i+1)
        local w=le and (a+256*b) or (256*a+b)
        i=i+2
        if w>=0xD800 and w<=0xDBFF then
            if i>#raw then return nil,"truncated surrogate" end
            local c,d=raw:byte(i,i+1)
            local low=le and (c+256*d) or (256*c+d)
            if low<0xDC00 or low>0xDFFF then return nil,"invalid surrogate pair" end
            w=0x10000+(w-0xD800)*1024+(low-0xDC00)
            i=i+2
        elseif w>=0xDC00 and w<=0xDFFF then return nil,"unpaired surrogate" end
        n=n+1
        out[n]=utf8cp(w)
    end
    return table.concat(out)
end
local function declaration(s)
    -- ASCII-compatible encoding declarations only (UTF-16 is decoded earlier).
    local d=s:match("^%s*<%?xml%s+([^?]-)%?>")
    return d and (d:match('encoding%s*=%s*"([^"]+)"')
            or d:match("encoding%s*=%s*'([^']+)'")) or nil
end
M.declaration=declaration
function M.decode(raw)
    if type(raw)~="string" then return nil,"not a byte string" end
    local bom
    local data=raw
    if raw:sub(1,3)=="\239\187\191" then
        bom="utf-8";data=raw:sub(4)
    elseif raw:sub(1,2)=="\255\254" then
        bom="utf-16le";data=raw:sub(3)
    elseif raw:sub(1,2)=="\254\255" then
        bom="utf-16be";data=raw:sub(3)
    end
    local xml,enc
    if bom=="utf-16le" or bom=="utf-16be" or
        (not bom and raw:sub(1,4)=="<\0?\0") or
        (not bom and raw:sub(1,4)=="\0<\0?") then
        local le=bom=="utf-16le" or (not bom and raw:sub(1,4)=="<\0?\0")
        local err
        xml,err=decode16(data,le)
        if not xml then return nil,err end
        enc=le and "utf-16le" or "utf-16be"
    else
        enc=bom or normal(declaration(data) or "utf-8")
        if enc=="utf-8" then
            if not utf8_valid(data) then return nil,"invalid UTF-8" end
            xml=data
        else
            local mapping=maps[enc]
            if not mapping then return nil,"unsupported XML charset: "..enc end
            local parts={}
            for i=1,#data do
                local ch=data:byte(i)
                if ch<128 then parts[i]=string.char(ch)
                else
                    local cp=mapping[ch-127]
                    if not cp or cp==0 then
                        return nil,"undefined character in "..enc.." at byte "..i
                    end
                    parts[i]=utf8cp(cp)
                end
            end
            xml=table.concat(parts)
        end
    end
    -- Validate declared encoding when a BOM mandates a different conversion.
    local decl=normal(declaration(xml) or "")
    if bom and decl~="" then
        if bom=="utf-8" and decl~="utf-8"
        or (bom:sub(1,6)=="utf-16" and decl~="utf-16"
            and decl~=bom) then return nil,"encoding conflicts with BOM" end
    end
    return xml,enc
end
